#!/usr/bin/env python3
"""Copy the Synty sprites/fonts referenced by game code + data into game/assets/ui/synty/.

Originals in SourceFiles/ are never modified; relative paths and filenames are preserved so every
imported file maps 1:1 back to its source (see docs/ASSET_MAPPING.md). Usage: python3 tools/import_assets.py
"""
import pathlib, re, shutil, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "SourceFiles"
DST = ROOT / "game" / "assets" / "ui" / "synty"
PATTERN = re.compile(r'"((?:HUD|MilitaryCombat|FX|Cursors|Badges|Samples|Icons_\w+|Core/[\w/]+|Fonts/[\w/]+)/[\w\-]+\.(?:png|ttf))"')

refs = set()
for f in list((ROOT / "game").rglob("*.gd")) + list((ROOT / "game" / "data").glob("*.json")):
    if ".godot" in f.parts:
        continue
    refs.update(PATTERN.findall(f.read_text()))
refs.add("Fonts/Oxanium/OFL.txt")

missing = []
converted = []
for rel in sorted(refs):
    s = SRC / rel
    if not s.exists():
        s = SRC / "Sprites" / rel  # sprite folders live under SourceFiles/Sprites/
    if not s.exists():
        missing.append(rel)
        continue
    d = DST / rel
    d.parent.mkdir(parents=True, exist_ok=True)
    if rel.startswith("Samples/") and "Screenshot" in rel:
        # converted copy: 5040x2160 vendor screenshots downscaled to 1920 px wide for menu backdrops
        if not d.exists():
            from PIL import Image
            with Image.open(s) as im:
                im.convert("RGB").resize((1920, round(im.height * 1920 / im.width)), Image.LANCZOS).save(d, optimize=True)
            converted.append(rel)
        continue
    if not d.exists() or d.stat().st_size != s.stat().st_size:
        shutil.copy2(s, d)
manifest = DST / "MANIFEST.txt"
manifest.write_text("# Files copied from SourceFiles/ (same relative path). Generated by tools/import_assets.py\n"
    "# Sample screenshots are converted copies (downscaled to 1920 px wide); everything else is byte-identical.\n"
    + "\n".join(sorted(refs - set(missing))) + "\n")
print(f"referenced={len(refs)} copied={len(refs) - len(missing)} missing={len(missing)}")
for m in missing:
    print("MISSING", m)
sys.exit(1 if missing else 0)
